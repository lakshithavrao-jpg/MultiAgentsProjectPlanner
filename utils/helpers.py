import re


def clean_filename(filename):

    filename = filename.strip().replace(" ", "_")

    filename = re.sub(
        r"[^A-Za-z0-9_-]",
        "",
        filename
    )

    return filename or "project"


def format_project_name(name):

    return name.strip().title()


def create_markdown_report(project, results):

    sections = [
        ("Project Details", str(project)),
        ("Requirement Analysis", results.get("requirements", "")),
        ("Software Architecture", results.get("architecture", "")),
        ("Project Management Plan", results.get("project_plan", "")),
        ("Final Proposal", results.get("proposal", ""))
    ]

    report = f"# {project['name']}\n\n"

    report += "Generated by NEXUS Agentic AI Project Planner\n\n"

    for title, content in sections:

        report += f"\n\n# {title}\n\n"
        report += str(content)

    return report